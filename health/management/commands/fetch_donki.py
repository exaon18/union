"""
python manage.py fetch_donki --days 30
    Download real NASA DONKI space-weather events (flares, SEP, CME, geomagnetic storms) for the
    last N days into SpaceWeatherEvent. Uses NASA_API_KEY (falls back to DEMO_KEY) on api.nasa.gov
    and the CCMC DONKI web service as a fallback. If DONKI can't be reached, the bundled cached
    snapshot (health/data/donki_snapshot.json) is loaded instead and labelled "snapshot".

    A new SEP event or X-class flare from the last 48 h also raises a cabin radiation alert
    citing the event.

python manage.py fetch_donki --since 2024-01-01 --write-snapshot
    Refresh the bundled snapshot (developers).
"""
import json
from datetime import date, timedelta

from django.core.management.base import BaseCommand
from django.utils import timezone

from health import donki


class Command(BaseCommand):
    help = "Fetch NASA DONKI space weather events (FLR, SEP, CME, GST)."

    def add_arguments(self, parser):
        parser.add_argument("--days", type=int, default=30)
        parser.add_argument("--since", help="YYYY-MM-DD (overrides --days)")
        parser.add_argument("--offline", action="store_true", help="only load the bundled snapshot")
        parser.add_argument("--write-snapshot", action="store_true",
                            help="also write health/data/donki_snapshot.json and frontend/js/donki-snapshot.js")
        parser.add_argument("--no-alerts", action="store_true")

    def handle(self, *args, **o):
        end = date.today()
        start = date.fromisoformat(o["since"]) if o["since"] else end - timedelta(days=o["days"])
        events, hosts, failed = [], set(), []
        if not o["offline"]:
            for t in donki.TYPES:
                try:
                    raw, used = donki.fetch_type(t, start, end, log=lambda m: self.stdout.write(m))
                    hosts.update(used)
                    events += [donki.normalize(t, r) for r in raw]
                    self.stdout.write(f"{t}: {len(raw)} events")
                except RuntimeError as exc:
                    failed.append(t)
                    self.stderr.write(self.style.WARNING(str(exc)))
        if events:
            n = donki.save_events(events, "live")
            self.stdout.write(self.style.SUCCESS(f"Saved {n} live DONKI events ({start}..{end}) from {', '.join(sorted(hosts))}"))
        if failed or o["offline"]:
            snap = donki.load_snapshot()
            n = donki.save_events(snap.get("events", []), "snapshot") if not events else 0
            self.stdout.write(self.style.WARNING(
                f"DONKI not reachable for {failed or 'all types (offline)'}: "
                + (f"loaded {n} events from the cached snapshot fetched {snap.get('fetched_at')}" if n else "kept live data")))
        if o["write_snapshot"] and events:
            self.write_snapshot(events, start, end, sorted(hosts))
        if not o["no_alerts"] and events:
            self.raise_alerts(events)
        st = donki.state(donki.stored_events()[0])
        self.stdout.write(f"Crew space-weather state: {st['level']} - {st['reason']}")

    def write_snapshot(self, events, start, end, hosts):
        # All SEP events, X flares and geomagnetic storms; M flares / fast CMEs from the last 180 days.
        recent = (end - timedelta(days=180)).isoformat()
        keep = [{k: v for k, v in e.items() if k not in ("note", "instruments")} for e in events
                if e["level"] == "critical" or e["type"] == "GST" or (e["level"] == "caution" and e["time"] >= recent)]
        snap = {"source": "NASA DONKI (" + ", ".join(hosts) + ")",
                "range": [start.isoformat(), end.isoformat()],
                "fetched_at": timezone.now().isoformat(timespec="seconds"),
                "note": "Cached snapshot of real DONKI events: all SEP events, X-class flares and geomagnetic storms in the range, "
                        "M-class flares and fast CMEs from its last 180 days. "
                        "Used when DONKI can't be reached; shown as 'cached'.",
                "events": sorted(keep, key=lambda e: e["time"], reverse=True)}
        donki.SNAPSHOT_FILE.write_text(json.dumps(snap, separators=(",", ":")))
        js = donki.SNAPSHOT_FILE.parent.parent.parent / "frontend" / "js" / "donki-snapshot.js"
        small = dict(snap, events=[{k: e.get(k) for k in ("id", "type", "time", "class", "kp", "speed", "link", "level", "label", "impact")}
                                   for e in snap["events"]][:500])
        js.write_text("/* Generated by `manage.py fetch_donki --write-snapshot`: cached real NASA DONKI events for mock mode. */\n"
                      "window.ASTRA_DONKI = " + json.dumps(small, separators=(",", ":")) + ";\n")
        self.stdout.write(self.style.SUCCESS(f"Wrote {donki.SNAPSHOT_FILE} ({len(keep)} events) and {js}"))

    def raise_alerts(self, events):
        from health.models import Alert
        now = timezone.now()
        for e in events:
            t = donki._dt(e["time"])
            if e["level"] != "critical" or not t or now - t > timedelta(hours=48):
                continue
            msg = f"Space weather: {e['label']} (NASA DONKI)"[:255]
            if Alert.objects.filter(astronaut=None, message=msg, created_at__gte=now - timedelta(days=3)).exists():
                continue
            Alert.objects.create(astronaut=None, system="radiation", level="red", message=msg,
                                 recommendation=f"{donki.SHELTER} Event {e['id']}."[:255])
            self.stdout.write(self.style.WARNING(f"Cabin alert raised for {e['id']}"))
